"""Recover original sponsor icon lookup, without game/device IO or hooks."""
from pathlib import Path
import argparse, hashlib, sys, struct
sys.dont_write_bytecode = True
sys.path.insert(0, str(Path(__file__).resolve().parent))
from world_body_trace import Image
from hud254_native import Machine
from unicorn.x86_const import UC_X86_REG_ESI, UC_X86_REG_EDI, UC_X86_REG_EIP
parser = argparse.ArgumentParser()
parser.add_argument('retail_root', type=Path)
parser.add_argument('--write-table', action='store_true')
args = parser.parse_args()
raw = (args.retail_root / 'speed.exe').read_bytes()
if hashlib.sha256(raw).hexdigest() != 'c0fad450912952f53809a54690d235aa8b4e25b9f46650693c7cbee1b4c074b7':
    raise SystemExit('original executable identity mismatch')
m = Machine(Image(raw))
m.run(0x68f1f0)
rows = [struct.unpack('<6I', bytes(m.uc.mem_read(0x744360 + i*24, 24))) for i in range(68)]
text = '// Original68F1F0 sponsor aliases and512294 icon lookup. Generated by\n// tools/career_decal_icons_native.py; no retail bytes are embedded.\n'
cases = 0
for index, a, b, c, icon, name in rows:
    assert index == cases//3
    for key in (a,b,c):
        m.uc.reg_write(UC_X86_REG_ESI,key)
        m.uc.reg_write(UC_X86_REG_EDI,0xdeadbeef)
        m.uc.emu_start(0x512294,0x5122bb,count=10000)
        assert m.uc.reg_read(UC_X86_REG_EIP) == 0x5122bb
        # Duplicate -1 entries follow first-match behavior, as in production.
        expected = next(r[4] for r in rows if key in r[1:4])
        assert m.uc.reg_read(UC_X86_REG_EDI) == expected
        cases += 1
    text += '{{{{0x{:08X}U,0x{:08X}U,0x{:08X}U}},0x{:08X}U}},\n'.format(a,b,c,icon)
path = Path(__file__).resolve().parent.parent / 'src/career_decal_icons.inc'
if args.write_table:
    path.write_text(text, encoding='ascii')
else:
    assert path.read_text(encoding='ascii') == text, 'sponsor icon table differs from original'
print('PASS original sponsor initializer, first-match alias lookup and generated table; cases=' + str(cases))
