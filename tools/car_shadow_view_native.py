"""Read-only PC USA 1.4 eView size, car LOD and silhouette-alpha witnesses."""
import argparse
import hashlib
import json
import struct
from pathlib import Path

from hud254_trace import PE
from physics256_native import Machine, STACK, bits


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--root', required=True, type=Path)
    parser.add_argument('--output', required=True, type=Path)
    parser.add_argument('--evidence', required=True, type=Path)
    args = parser.parse_args()
    root = args.root.resolve()
    for output in (args.output, args.evidence):
        if output.exists() or root == output.resolve() or root in output.resolve().parents:
            parser.error('outputs must be fresh and outside retail')
    data = (root / 'speed.exe').read_bytes()
    digest = hashlib.sha256(data).hexdigest()
    assert digest == 'c0fad450912952f53809a54690d235aa8b4e25b9f46650693c7cbee1b4c074b7'
    image = PE(data)
    view, camera, point, frame, trampoline = (0x1100000, 0x1101000, 0x1102000,
                                            0x1103000, 0x1104000)
    result = []
    lines = ['// Generated by tools/car_shadow_view_native.py; original PC USA 1.4.',
             'struct ShadowViewNative { unsigned width, fov; float position[3];',
             '    bool two_players; float height, scale; int pixels; unsigned lod, alpha; };',
             'static const ShadowViewNative shadow_view_native[] = {']
    cases = [(640, 13020, (x, 0, 0), False, 0.0)
             for x in (0, 3, 4.5, 5, 10, 20, 30, 35, 40, 50, 60, 100, 200)]
    cases += [(640, 13020, p, False, 0.0)
              for p in ((-3.01, 10, 0), (-3, 10, 0), (-2, 10, 0), (30, 20, 5))]
    cases += [(width, fov, (40, 0, 0), split, height)
              for width, fov in ((640, 10000), (1280, 13020), (1280, 16384),
                                 (512, 13020), (512, 10000), (512, 16384), (512, 0))
              for split in (False, True) for height in (0.0, 0.5)]
    cases += [(1280, 13020, (x, 0, 0), False, 0.0) for x in (90, 200)]
    cases += [(512, 13020, (x, 0, 0), False, 0.0) for x in (10, 30, 90, 200)]
    for width, fov, position, split, height in cases:
        m = Machine(image)
        m.allowed = [(0x40dcb0, 0x40dcf6), (0x564b10, 0x564ba6),
                     (0x545180, 0x545210), (0x674898, 0x67490d),
                     (0x56dc6c, 0x56dc8a), (0x56e0ad, 0x56e103),
                     (0x56e74c, 0x56e799), (trampoline, trampoline + 32)]
        m.put(0x701034, width)
        m.uc.mem_write(trampoline, b'\xd9\x1d' + struct.pack('<I', trampoline + 64) + b'\xc3')
        m.run(0x40dcb0, eax=fov)
        m.run(trampoline)
        scale = m.get(trampoline + 64, 'f')
        m.put(view + 0xc, scale, 'f')
        m.put(view + 0x40, camera)
        m.uc.mem_write(camera + 0x50, struct.pack('<3f', 1, 0, 0))
        m.uc.mem_write(point, struct.pack('<3f', *position))
        m.run(0x545180, (bits(3.0),), ecx=point, edx=view)
        pixels = m.reg('eax')
        if split:
            m.put(STACK + 0x10, pixels)
            m.run(0x56dc6c, end=0x56dc8a, ebp=frame)
            pixels = m.reg('eax')
        m.put(STACK + 0x10, pixels)
        m.put(frame + 0x30, int(split))
        m.put(frame + 0x2c, int(split))
        m.run(0x56e0ad, end=0x56e103, ebp=frame)
        lod = m.reg('esi')
        alpha = 0
        if pixels >= 4 and lod <= 2:
            # Preserve the original cmp esi,2 flags across the FPU alpha work.
            start = trampoline + 16
            m.uc.mem_write(start, b'\x83\xfe\x02\xe9' +
                           struct.pack('<i', 0x56e74c - (start + 8)))
            m.put(STACK + 0x10, height, 'f')
            m.put(STACK + 0x34, float(pixels), 'f')
            m.run(start, end=0x56e799, esi=lod)
            alpha = m.reg('eax')
        assert not m.events
        result.append(dict(width=width, fov=fov, position=position, two_players=split,
                           height=height, scale=scale, pixels=pixels, lod=lod,
                           alpha=alpha, hooks=m.events))
        point_text = '{' + ','.join(repr(float(x)) + 'F' for x in position) + '}'
        lines.append('    {%d,%d,%s,%s,%sF,%sF,%d,%d,%d},' %
                     (width, fov, point_text, str(split).lower(), repr(height),
                      repr(scale), pixels, lod, alpha))
    lines += ['};', '']
    args.output.write_text('\n'.join(lines), encoding='ascii')
    args.evidence.write_text(json.dumps(dict(exe_sha256=digest,
        scope='Original scale40DCB0, size545180, split56DC6C, LOD56E0AD and alpha56E74C; synthetic view, no game launch.',
        cases=result), indent=2) + '\n', encoding='ascii')
    print('PASS original PC shadow view: %d cases, no call hooks' % len(result))


if __name__ == '__main__':
    main()
