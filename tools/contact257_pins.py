"""Generate application, response and pair pins from contact257_trace.py evidence."""
import argparse
import hashlib
import json
from pathlib import Path


def number(value):
    return float(value).hex()+'F'


def vector(values):
    return '{'+', '.join(number(v) for v in values)+'}'


def body(value):
    matrix=value['inverse_inertia']
    rows=[matrix[i:i+3] for i in (0,4,8)]
    return '{'+', '.join((str(int(value['body'],16)),number(value['inverse_mass']),
        str(value['state']),number(value['state_timer']),vector(value['linear_momentum']),
        vector(value['angular_momentum']),vector(value['position']),
        '{{'+', '.join(vector(row) for row in rows)+'}}',vector(value['velocity']),
        vector(value['angular_velocity'])))+'}'


def generate(report):
    if report['schema']!='contact256-v1' or report['input']['sha256']!=(
        'C0FAD450912952F53809A54690D235AA8B4E25B9F46650693C7CBEE1B4C074B7'):
        raise ValueError('unsupported original evidence')
    if report['runtime_capture'] is not None or report['final_published_kinematics'] is not None:
        raise ValueError('unexpected evidence boundary')
    lines=['// Generated by tools/contact257_pins.py from authenticated original execution.',
           '// Synthetic memory only; PR308 reference 988bc892f643c463ba02a8c83e33b48918f889c3.',
           'static const ApplicationPin kApplicationPins[] = {']
    for case in report['native']['cases']:
        for event in case['applied']:
            before=next(b for b in event['bodies'] if b['body']==event['body'])
            after=next(b for b in event['after'] if b['body']==event['body'])
            lines.append('    {"%s/%s", %s, %s, %s, %s, %s},'%(
                case['name'],event['return_address'],body(before),vector(event['impulse']),
                vector(event['arm']),vector(after['linear_momentum']),vector(after['angular_momentum'])))
    lines+=['};','static const RecordPin kRecordPins[] = {']
    for case in report['native']['cases']:
        if case['hits']:
            hit=case['hits'][0]
            lines.append('    {"%s", %s, %s, %s, %s, %s},'%(
                case['name'],vector(case['input']['accumulated']),number(case['input']['magnitude_sum']),
                vector(hit['impulse']),vector(case['accumulated']),number(case['magnitude_sum'])))
    lines+=['};','static const PairPin kPairPins[] = {']
    for case in report['native']['cases']:
        a,b=case['before'];aa,bb=case['after']
        hit=case['hits'][0] if case['hits'] else None
        bounds=case.get('retail_prerequisites',{}).get('physical_lateral_bounds')
        bounds_text='{{'+', '.join('{'+', '.join(number(v) for v in row)+'}'
                                  for row in (bounds or ((0,0),(0,0))))+'}}'
        lines.append('    {"%s", %s, %s, {%s,%s}, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s},'%(
            case['name'],body(a),body(b),vector(case['geometry']['normal']),vector(case['geometry']['point']),
            'true' if case['input']['solver_invoked'] else 'false',
            vector(hit['impulse'] if hit else (0,0,0)),number(hit['tangent_speed'] if hit else 0),
            vector(case['input']['accumulated']),number(case['input']['magnitude_sum']),
            body(aa),body(bb),number(case['magnitude_sum']),
            case.get('world_seed_before',12345),case.get('world_seed_after',0),
            'true' if bounds else 'false',bounds_text,
            'true' if case.get('record_gate_before') else 'false',
            vector(case['witness']['witness_a']),vector(case['witness']['witness_b'])))
    lines+=['};','static const RefreshPin kRefreshPins[] = {']
    for case in report['native']['refresh_cases']:
        lines.append('    {"%s", %s, %s, %s, %s},'%(case['name'],
            body(case['before']),number(case['raw_mass']),number(case['speed_limit']),
            body(case['after'])))
    return '\n'.join(lines+['};',''])


def main():
    p=argparse.ArgumentParser(description=__doc__)
    p.add_argument('--report',required=True,type=Path)
    p.add_argument('--output',required=True,type=Path)
    args=p.parse_args()
    report=json.loads(args.report.read_text(encoding='ascii'))
    for name in ('contact257_trace.py','contact257_pins.py','contact257_retail.py'):
        actual=hashlib.sha256(Path(__file__).with_name(name).read_bytes()).hexdigest().upper()
        if report.get('worker_tool_hashes',{}).get(name)!=actual:
            raise ValueError('worker tool hash mismatch: '+name)
    text=generate(report)
    with args.output.open('x',encoding='ascii',newline='\n') as out: out.write(text)
    print('PASS: bounded original pins generated; synthetic evidence only')


if __name__=='__main__': main()
