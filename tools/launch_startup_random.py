"""Execute PC1.4 track-streamer, sound and world RNG boundaries offline.

No game is started. The caller supplies the global state after the traffic
roster and a current TrackInfo number. Constructors outside the three named
slices, track loading and the frame scheduler are not executed.
"""
import argparse
import hashlib
import json
from pathlib import Path

from launch_traction_boundary import PC_HASH
from physics256_native import Machine
from world_body_trace import Image


RANGES = ((0x4445FC, 0x44463C), (0x51CEAF, 0x51CEDC),
          (0x41F7C9, 0x41F891))


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--retail', type=Path, required=True)
    parser.add_argument('--out', type=Path, required=True)
    parser.add_argument('--write-fixture', action='store_true')
    args = parser.parse_args()
    repo = Path(__file__).resolve().parents[1]
    output = args.out.resolve()
    try:
        relative = output.relative_to(repo)
    except ValueError:
        parser.error('output must stay inside this checkout')
    if not relative.parts or not relative.as_posix().isascii() or output.exists():
        parser.error('fresh ASCII output directory required')
    data = (args.retail/'speed.exe').read_bytes()
    if hashlib.sha256(data).hexdigest() != PC_HASH:
        parser.error('unsupported PC executable')
    image = Image(data)
    machine = Machine(image)
    machine.allowed = list(RANGES)
    track_info, streamer, world = 0x1100000, 0x1101000, 0x1102000
    machine.put(0x736174, track_info)
    rows = []
    seeds = [0, 1, 0x7FFFFFFE, 0x7FFFFFFF, 0x80000000, 0xFFFFFFFF,
             0x12345678, 0x1C9D5727, 0x8896F627]
    tracks = [0, 1001, 1008, 1099, 1100, 1101, 1102, 1103, 1104,
              1105, 1106, 1107, 1108, 1109, 1110, 1111, 32767, 65535]
    for track in tracks:
        for seed in seeds:
            machine.put(track_info+0x6C, track, 'H')
            machine.put(0x6F227C, seed)
            machine.run(RANGES[0][0], end=RANGES[0][1], eax=streamer, ebx=0)
            after_streamer = machine.get(0x6F227C)
            machine.run(RANGES[1][0], end=RANGES[1][1])
            sound = machine.get(0x7356D8)
            before_world = machine.get(0x6F227C)
            machine.run(RANGES[2][0], end=RANGES[2][1], esi=world, ebx=0)
            next_global = machine.get(0x6F227C)
            assert sound == after_streamer
            assert machine.get(world+0x2D0) == before_world % 0x7FFFFFFF
            rows.append([track, seed, sound, before_world, next_global])
    assert not machine.events
    fixture = ('// Generated by tools/launch_startup_random.py from authenticated PC1.4.\n'
               '// Supplied TrackInfo/global state; streamer, sound and world slices; no hooks.\n'
               'static constexpr unsigned kNativeLaunchRandom[][5]={\n')
    fixture += ''.join('    {'+','.join('0x%08XU' % n for n in row)+'},\n'
                       for row in rows)
    fixture += '};\n'
    fixture_path = repo/'tests/launch_startup_random_native.inc'
    if args.write_fixture:
        fixture_path.write_bytes(fixture.encode('ascii'))
    elif fixture_path.read_bytes() != fixture.encode('ascii'):
        raise RuntimeError('native launch RNG fixture differs')
    output.mkdir(parents=True)
    report = dict(executable_sha256=PC_HASH,
                  tool_sha256=hashlib.sha256(Path(__file__).read_bytes()).hexdigest(),
                  source_ranges=[dict(start=hex(a), end=hex(b),
                                      sha256=hashlib.sha256(image.read(a, b-a)).hexdigest())
                                 for a, b in RANGES],
                  rows=rows, hooks=machine.events,
                  boundary=__doc__)
    (output/'native.json').write_bytes((json.dumps(report, indent=2)+'\n').encode('ascii'))
    print('PASS original launch RNG slices:', len(rows), 'rows; no hooks')


if __name__ == '__main__':
    main()
