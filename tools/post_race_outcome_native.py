"""Bounded original5A2F10 ordinary-event win predicate.

Executes the authenticated PC1.4 USA bytes on supplied terminal racer records.
No original process, files or saves are modified. Tournament aggregation and
time-trial deadlines have separate native witnesses; this covers places1..4
and normal/knockout/blown-engine/totaled/timeup terminal results only.
"""
from pathlib import Path
import sys,hashlib,argparse
sys.dont_write_bytecode=True
sys.path.insert(0,str(Path(__file__).resolve().parent))
from event0_trace import Image
from hud254_native import Machine
from unicorn import UC_HOOK_CODE
from unicorn.x86_const import UC_X86_REG_EAX,UC_X86_REG_ECX
parser=argparse.ArgumentParser();parser.add_argument('--root',type=Path,required=True)
raw=(parser.parse_args().root/'speed.exe').read_bytes()
assert hashlib.sha256(raw).hexdigest()=='c0fad450912952f53809a54690d235aa8b4e25b9f46650693c7cbee1b4c074b7'
image=Image(raw);image.sections=[(a,s,r)for a,s,r,n in image.sections]
rows=[]
for status in(1,3,6,7,8):
    for place in range(1,5):
        m=Machine(image);event=0x1001000;race=event+4
        m.write(event+0x5868,1);m.write(race+0x14,4);m.write(race+0xb08,4)
        places=[place]+[p for p in range(1,5)if p!=place]
        for actor,position in enumerate(places):
            record=race+0x28+actor*0x15c
            m.write(record,position);m.write(record+4,actor);m.write(record+8,status if actor==0 else 1)
        m.run(0x5a2f10,(event,0))
        rows.append([status,place,m.uc.reg_read(UC_X86_REG_EAX)&255])
assert len(rows)==20
lines=['// Generated by post_race_outcome_native.py from original5A2F10 bytes.',
       'struct NativePostOutcomeCase {unsigned status,place,won;};',
       'constexpr NativePostOutcomeCase kNativePostOutcome[]={']
lines+=['    {'+','.join(map(str,row))+'},'for row in rows];lines+=['};','']
Path('tests/post_race_outcome_native.inc').write_text('\n'.join(lines),encoding='ascii')
print('PASS20 original5A2F10 terminal status/place reward decisions')

# Original4CD3E0 table lookup and request dispatch; only the speech sink is
# stubbed. Negative results mean no request, not a failed native execution.
m=Machine(image);m.uc.mem_write(0x51c830,b'\xc2\x04\x00');requests=[]
def capture(uc,address,size,data):
    if address==0x51c830:requests.append(uc.reg_read(UC_X86_REG_ECX))
m.uc.hook_add(UC_HOOK_CODE,capture);voices=[]
for event in range(112):
    requests.clear();m.run(0x4cd3e0,(),{UC_X86_REG_ECX:event})
    assert len(requests)<=1
    voices.append([event,requests[0]if requests else -1])
lines=['// Generated from original4CD3E0 bytes; speech output is a captured sink.',
       'struct NativePostSpeechCase {unsigned event;int request;};',
       'constexpr NativePostSpeechCase kNativePostSpeech[]={']
lines+=['    {'+','.join(map(str,row))+'},'for row in voices];lines+=['};','']
Path('tests/post_race_speech_native.inc').write_text('\n'.join(lines),encoding='ascii')
print('PASS112 original4CD3E0 conditional career speech requests')
