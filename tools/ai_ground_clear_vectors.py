import argparse
import hashlib
import json
import struct
from pathlib import Path
from physics256_native import Machine, STOP, bits
from world_body_trace import Image

p = argparse.ArgumentParser()
p.add_argument('--root', type=Path, required=True)
p.add_argument('--out', type=Path, required=True)
a = p.parse_args()
out = a.out.resolve()
relative = out.relative_to(Path.cwd())
assert str(relative).isascii() and relative.parts[0].startswith('build')
assert a.root.resolve() not in out.parents
out.mkdir(exist_ok=False, parents=True)
exe = (a.root / 'speed.exe').read_bytes()
bun = (a.root / 'Global/GLOBALB.BUN').read_bytes()
assert hashlib.sha256(exe).hexdigest() == 'c0fad450912952f53809a54690d235aa8b4e25b9f46650693c7cbee1b4c074b7'
assert hashlib.sha256(bun).hexdigest() == '39df38fac2be7ca0f0d0a92e0113caaeda5b1c60e14436c612b3d0874afc8db9'
image = Image(exe)
queries = []
for point in ((0, 0, .25), (983.049011, -243.833969, 59.559338), (1, 2, -7)):
    m = Machine(image)
    cache, hub, normal, material, hit, scalar = [0x1100000 + i * 0x1000 for i in range(6)]
    m.allowed = [(0x440a40, 0x440c74), (0x577060, 0x577209), (0x40cb70, 0x40cb7b)]
    for offset, value in ((0, -10000), (4, -10000), (8, 10000), (12, 10000)):
        m.put(cache + offset, value, 'f')
    for j, v in enumerate(point):
        m.put(hub + 4*j, v, 'f')
    m.run(0x440a40, (cache, hub, material, normal, hit))
    # Capture ST0 after the actual function returned, without replacing it.
    capture = STOP + 0x100
    m.uc.mem_write(capture, b'\xd9\x1d' + struct.pack('<I', scalar) + b'\xc3')
    m.allowed.append((capture, capture + 7))
    m.run(capture)
    height = m.get(scalar)
    expected = [height] + [m.get(normal + 4*j) for j in range(3)]
    assert expected == [bits(point[2]), 0, 0, bits(-1)]
    assert m.get(hit) == 0 and m.get(material) == 1 and not m.events
    m.put(0x73b14c, 0x73b14c)  # Empty original intrusive dynamic surface list.
    m.run(0x577060, (hit, cache, height, hub, material, normal, 0))
    m.run(capture)
    assert [m.get(scalar)] + [m.get(normal+4*j) for j in range(3)] == expected
    assert not m.events
    queries.append(dict(point=point, expected=expected, hooks=m.events))

m = Machine(image)
engine, setup, body = 0x1100000, 0x1101000, 0x1102000
m.allowed = [(0x475097, 0x475179), (0x475a00, 0x475bea)]
m.uc.mem_write(setup, bun[1736752+0x110:1736752+3216])
m.run(0x475097, end=0x475179, esi=engine, ebp=setup)
m.put(engine+0x18, setup)
m.put(engine+0x14, body)
for j in range(3):
    m.put(body+0x30+j*20, 1, 'f')
m.put(0x6f0738, 1/120, 'f')
mask = 0
def query(x):
    heights, hubs = x.reg('ecx'), x.reg('edx')
    for k in range(4):
        clear = bool(mask & (1 << k))
        x.put(heights+4*k, .25 if clear else 0, 'f')
        for j, v in enumerate((0, 0, .25)):
            x.put(hubs+16*k+4*j, v, 'f')
        for j, v in enumerate((0, 0, -1 if clear else 1)):
            x.put(engine+0xe0+16*k+4*j, v, 'f')
    x.ret(4)
m.hook(0x475bf0, 'supplied-hit-or-authenticated-clear-query', callback=query)
rows = []
for mask in (0, 2, 15, 0):
    m.run(0x475a00, (engine,))
    expected = [m.get(engine+base+4*k) for k in range(4)
                for base in (0x34, 0x44, 0x54, 0x64, 0xc8)]
    rows.append(dict(mask=mask, expected=expected))
report = dict(queries=queries, transitions=rows, hooks=m.events,
              boundary='Empty static cache and dynamic list execute original functions without hooks. Strut sequence uses supplied query outputs and authentic stock setup; no live retail lookup or trajectory equivalence.')
(out/'evidence.json').write_text(json.dumps(report, indent=2)+'\n', encoding='ascii')
lines = ['// Generated by tools/ai_ground_clear_vectors.py. Original475A00, supplied query outputs.',
         '// Authentic speed.exe c0fad450912952f53809a54690d235aa8b4e25b9f46650693c7cbee1b4c074b7.']
lines += ['{'+str(r['mask'])+', {{'+','.join('0x%08Xu'%x for x in r['expected'])+'}}},' for r in rows]
(out/'ai_ground_clear_native.inc').write_text('\n'.join(lines)+'\n', encoding='ascii')
print('PASS: 3 original clear queries, empty dynamic pass-through, 4 strut transitions')
